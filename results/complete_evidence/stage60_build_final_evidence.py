from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path
from typing import Any


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def is_true(value: Any) -> bool:
    return str(value).strip().lower() == "true"


def quality_relation(row: dict[str, str]) -> int:
    selected = (int(row["selected_swap"]), int(row["selected_depth"]))
    baseline = (
        int(row["lightsabre_swap"]),
        int(row["lightsabre_depth"]),
    )
    return -1 if selected < baseline else 1 if selected > baseline else 0


def dataset_metrics(label: str, rows: list[dict[str, str]]) -> dict[str, Any]:
    ls = sum(int(row["lightsabre_swap"]) for row in rows)
    oaabr = sum(int(row["oaabr_swap"]) for row in rows)
    dual = sum(int(row["safe_dual_swap"]) for row in rows)
    selected = sum(int(row["selected_swap"]) for row in rows)
    swap_wins = sum(
        int(row["selected_swap"]) < int(row["lightsabre_swap"])
        for row in rows
    )
    swap_losses = sum(
        int(row["selected_swap"]) > int(row["lightsabre_swap"])
        for row in rows
    )
    relations = [quality_relation(row) for row in rows]
    return {
        "dataset": label,
        "cases": len(rows),
        "lightsabre_swap": ls,
        "native_oaabr_swap": oaabr,
        "safe_dual_swap": dual,
        "selected_swap": selected,
        "gain_vs_lightsabre": ls - selected,
        "relative_gain_pct": 100.0 * (ls - selected) / ls if ls else 0.0,
        "native_oaabr_gap_vs_lightsabre": oaabr - ls,
        "swap_wins": swap_wins,
        "swap_ties": len(rows) - swap_wins - swap_losses,
        "swap_losses": swap_losses,
        "quality_wins": relations.count(-1),
        "quality_ties": relations.count(0),
        "quality_losses": relations.count(1),
        "semantic_passed": sum(
            is_true(row["semantic_equivalent"]) for row in rows
        ),
        "topology_passed": sum(is_true(row["topology_valid"]) for row in rows),
        "metric_passed": sum(is_true(row["metric_valid"]) for row in rows),
        "selected_backends": dict(
            Counter(row["selected_backend"] for row in rows)
        ),
    }


def runtime_row(
    dataset: str,
    baseline_label: str,
    baseline_seconds: float,
    persistent_seconds: float,
    processes: int,
    avoided_restarts: int,
) -> dict[str, Any]:
    return {
        "dataset": dataset,
        "baseline": baseline_label,
        "baseline_seconds": baseline_seconds,
        "persistent_seconds": persistent_seconds,
        "speedup": baseline_seconds / persistent_seconds,
        "wall_reduction_pct": 100.0 * (1.0 - persistent_seconds / baseline_seconds),
        "persistent_processes": processes,
        "avoided_process_restarts": avoided_restarts,
    }


def latex_escape(text: Any) -> str:
    return (
        str(text)
        .replace("\\", r"\textbackslash{}")
        .replace("_", r"\_")
        .replace("%", r"\%")
        .replace("&", r"\&")
    )


def write_latex(
    path: Path,
    quality_rows: list[dict[str, Any]],
    runtime_rows: list[dict[str, Any]],
    v6_summary: dict[str, Any],
) -> None:
    lines = [
        r"% Auto-generated by Stage 60.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{冻结组合路由器的 SWAP 结果}",
        r"\label{tab:final-swap}",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"数据集 & 实例数 & LightSABRE & 原生 OAABR & 安全双路 & 最终选择 & 改善 \\",
        r"\midrule",
    ]
    for row in quality_rows:
        lines.append(
            f"{latex_escape(row['dataset'])} & {row['cases']} & "
            f"{row['lightsabre_swap']} & {row['native_oaabr_swap']} & "
            f"{row['safe_dual_swap']} & {row['selected_swap']} & "
            f"{row['gain_vs_lightsabre']} "
            f"({row['relative_gain_pct']:.2f}\\%) \\\\"
        )
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
            r"\begin{table}[htbp]",
            r"\centering",
            r"\caption{持久分片带来的墙钟时间改善}",
            r"\label{tab:persistent-runtime}",
            r"\begin{tabular}{lrrrr}",
            r"\toprule",
            r"数据集 & 基准/s & 持久分片/s & 加速比 & 降幅 \\",
            r"\midrule",
        ]
    )
    for row in runtime_rows:
        lines.append(
            f"{latex_escape(row['dataset'])} & "
            f"{row['baseline_seconds']:.3f} & "
            f"{row['persistent_seconds']:.3f} & "
            f"{row['speedup']:.3f}$\\times$ & "
            f"{row['wall_reduction_pct']:.2f}\\% \\\\"
        )
    ci_low, ci_high = v6_summary["bootstrap"]["ci95"]
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
            r"\begin{table}[htbp]",
            r"\centering",
            r"\caption{V6 预注册盲测的统计结论}",
            r"\label{tab:v6-inference}",
            r"\begin{tabular}{lr}",
            r"\toprule",
            r"指标 & 数值 \\",
            r"\midrule",
            f"平均归一化 SWAP gap & {v6_summary['mean_normalized_gap']:+.6f} \\\\",
            f"Bootstrap 95\\% CI & [{ci_low:+.6f}, {ci_high:+.6f}] \\\\",
            (
                "SWAP 胜/平/负 & "
                f"{v6_summary['swap_win_tie_loss']['win']}/"
                f"{v6_summary['swap_win_tie_loss']['tie']}/"
                f"{v6_summary['swap_win_tie_loss']['loss']} \\\\"
            ),
            (
                "质量胜/平/负 & "
                f"{v6_summary['quality_win_tie_loss']['win']}/"
                f"{v6_summary['quality_win_tie_loss']['tie']}/"
                f"{v6_summary['quality_win_tie_loss']['loss']} \\\\"
            ),
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


