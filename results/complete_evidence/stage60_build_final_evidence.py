def main() -> None:
    parser = argparse.ArgumentParser(
        description="Stage 60: build final OAABR evidence and paper tables"
    )
    parser.add_argument("--v5-cases", type=Path, required=True)
    parser.add_argument("--v5-stage57-summary", type=Path, required=True)
    parser.add_argument("--v5-stage58-summary", type=Path, required=True)
    parser.add_argument("--v6-cases", type=Path, required=True)
    parser.add_argument("--v6-stage56-summary", type=Path, required=True)
    parser.add_argument("--v6-stage59-summary", type=Path, required=True)
    parser.add_argument("--v6-groups", type=Path, required=True)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("results/stage60_final_evidence"),
    )
    args = parser.parse_args()

    input_paths = [
        args.v5_cases,
        args.v5_stage57_summary,
        args.v5_stage58_summary,
        args.v6_cases,
        args.v6_stage56_summary,
        args.v6_stage59_summary,
        args.v6_groups,
    ]
    for path in input_paths:
        if not path.is_file():
            raise FileNotFoundError(path)
    if args.output_dir.exists():
        raise FileExistsError(
            f"output directory already exists; use a fresh path: {args.output_dir}"
        )
    args.output_dir.mkdir(parents=True)

    v5_rows = read_csv(args.v5_cases)
    v6_rows = read_csv(args.v6_cases)
    stage57 = read_json(args.v5_stage57_summary)
    stage58 = read_json(args.v5_stage58_summary)
    stage56 = read_json(args.v6_stage56_summary)
    stage59 = read_json(args.v6_stage59_summary)
    group_rows = read_csv(args.v6_groups)

    if len(v5_rows) != 60 or len(v6_rows) != 120:
        raise ValueError("expected 60 V5 cases and 120 V6 cases")
    if not stage56.get("passed") or not stage59.get("passed"):
        raise ValueError("Stage 56 and Stage 59 must both be PASSED")
    if int(stage58.get("quality_mismatches", -1)) != 0:
        raise ValueError("V5 Stage 58 must have zero quality mismatches")

    quality = [
        dataset_metrics("V5 engineering check", v5_rows),
        dataset_metrics("V6 preregistered blind", v6_rows),
    ]
    if quality[0]["selected_swap"] != int(
        stage58["totals"]["selected_swap"]
    ):
        raise ValueError("V5 case totals disagree with Stage 58 summary")
    if quality[1]["selected_swap"] != int(
        stage56["totals"]["selected_swap"]
    ):
        raise ValueError("V6 case totals disagree with Stage 56 summary")

    runtime = [
        runtime_row(
            dataset="V5",
            baseline_label="Stage 57 per-case processes",
            baseline_seconds=float(stage57["parallel_wall_seconds"]),
            persistent_seconds=float(stage58["parallel_wall_seconds"]),
            processes=int(stage58["persistent_processes"]),
            avoided_restarts=int(stage58["avoided_process_restarts"]),
        ),
        runtime_row(
            dataset="V6",
            baseline_label="Stage 55 sequential",
            baseline_seconds=float(
                stage59["runtime"]["sequential_wall_seconds"]
            ),
            persistent_seconds=float(
                stage59["runtime"]["persistent_wall_seconds"]
            ),
            processes=int(stage59["runtime"]["persistent_processes"]),
            avoided_restarts=int(
                stage59["runtime"]["avoided_process_restarts"]
            ),
        ),
    ]

    quality_path = args.output_dir / "quality_summary.csv"
    runtime_path = args.output_dir / "runtime_summary.csv"
    groups_path = args.output_dir / "v6_group_summary.csv"
    latex_path = args.output_dir / "paper_tables.tex"
    report_path = args.output_dir / "FINAL_EVIDENCE_REPORT.md"
    write_csv(quality_path, quality)
    write_csv(runtime_path, runtime)
    write_csv(groups_path, group_rows)
    write_latex(latex_path, quality, runtime, stage56)
    write_report(report_path, quality, runtime, stage56, stage59)

    outputs = [
        quality_path,
        runtime_path,
        groups_path,
        latex_path,
        report_path,
    ]
    manifest = {
        "stage": 60,
        "purpose": "final frozen evidence and paper tables",
        "passed": True,
        "inputs": {
            str(path.resolve()): sha256(path) for path in input_paths
        },
        "outputs": {
            str(path.resolve()): sha256(path) for path in outputs
        },
        "quality": quality,
        "runtime": runtime,
        "v6_inference": {
            "mean_normalized_gap": stage56["mean_normalized_gap"],
            "bootstrap": stage56["bootstrap"],
            "swap_win_tie_loss": stage56["swap_win_tie_loss"],
            "quality_win_tie_loss": stage56["quality_win_tie_loss"],
        },
        "stage59_mismatches": stage59["mismatches"],
    }
    manifest_path = args.output_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    hashes_path = args.output_dir / "SHA256SUMS.txt"
    hashes_path.write_text(
        "".join(
            f"{sha256(path)}  {path}\n"
            for path in [*outputs, manifest_path]
        ),
        encoding="utf-8",
    )

    blind = quality[1]
    print("===== Stage 60 final evidence =====")
    print("V5 selected / LightSABRE:", quality[0]["selected_swap"], "/", quality[0]["lightsabre_swap"])
    print("V6 selected / LightSABRE:", blind["selected_swap"], "/", blind["lightsabre_swap"])
    print("V6 relative gain:", f"{blind['relative_gain_pct']:.2f}%")
    print(
        "V6 bootstrap 95% CI:",
        stage56["bootstrap"]["ci95"],
    )
    print("V5 runtime speedup:", round(runtime[0]["speedup"], 3))
    print("V6 runtime speedup:", round(runtime[1]["speedup"], 3))
    print("Stage 56 PASSED:", stage56["passed"])
    print("Stage 59 PASSED:", stage59["passed"])
    print("FINAL EVIDENCE PASSED: True")
    print("report:", report_path.resolve())
    print("tables:", latex_path.resolve())
    print("manifest:", manifest_path.resolve())
    print("hashes:", hashes_path.resolve())


if __name__ == "__main__":
    main()
